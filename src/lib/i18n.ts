export const LANGS = ['en', 'ar'] as const;
export type Lang = (typeof LANGS)[number];

export function isLang(value: unknown): value is Lang {
  return value === 'en' || value === 'ar';
}

export const dir = (lang: Lang) => (lang === 'ar' ? 'rtl' : 'ltr');

/** Locale for dates and numbers. Arabic uses Western digits, as is common in Lebanon (pending the reviewer's approval). */
export const locale = (lang: Lang) => (lang === 'ar' ? 'ar-LB-u-nu-latn' : 'en-GB');

/** A text in the visitor's language, plus the language it is actually in (English when the Arabic is empty). */
export interface Localized {
  text: string;
  lang: Lang;
}

/** Pick `<field>_<lang>` from a record, falling back to English when the Arabic is empty. */
export function pick(record: object | null | undefined, field: string, lang: Lang): Localized {
  const row = record as Record<string, unknown> | null | undefined;
  const own = String(row?.[`${field}_${lang}`] ?? '').trim();
  if (own || lang === 'en') return { text: own, lang };
  return { text: String(row?.[`${field}_en`] ?? '').trim(), lang: 'en' };
}

